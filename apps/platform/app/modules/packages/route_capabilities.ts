/** The capability of the tenant route `name`, or undefined for an unknown one. */
export function capabilityOf(name: string | undefined): Capability | undefined {
	if (name === undefined || !Object.hasOwn(ROUTE_CAPABILITIES, name)) {
		return undefined;
	}
	return ROUTE_CAPABILITIES[name as TenantRouteName];
}
